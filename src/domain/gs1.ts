export function digitsOnly(value: string): string {
  return value.replace(/\D/g, '');
}

export function isValidLength(barcode: string): boolean {
  const len = digitsOnly(barcode).length;
  return len === 13 || len === 8;
}

/** EAN-13 / EAN-8 / EAN-14 checksum check. */
export function isValidChecksum(barcode: string): boolean {
  const digits = digitsOnly(barcode);
  if (digits.length !== 13 && digits.length !== 8) return false;
  let sum = 0;
  for (let i = digits.length - 2; i >= 0; i--) {
    const weight = (digits.length - 1 - i) % 2 === 0 ? 1 : 3;
    sum += (digits.charCodeAt(i) - 48) * weight;
  }
  const check = (10 - (sum % 10)) % 10;
  return check === digits.charCodeAt(digits.length - 1) - 48;
}

/** Country/region by leading barcode digits (3 digits, then 2). */
export function countryName(barcode: string): string | null {
  const digits = digitsOnly(barcode);
  if (digits.length < 2) return null;
  return threeDigitCountry[digits.slice(0, 3)] ?? twoDigitCountry[digits.slice(0, 2)] ?? null;
}
